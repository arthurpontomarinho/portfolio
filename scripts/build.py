#!/usr/bin/env python3
"""Build the portfolio data + optimized images.

Reads  content/projects.json  (the single source of truth you edit)
Reads  acervo/...             (original, full-size files — not versioned)
Writes assets/img/<slug>/     (web-optimized JPGs + thumbs — versioned)
Writes content/data.js        (what the website loads)

Usage:  python3 scripts/build.py          # incremental
        python3 scripts/build.py --clean  # rebuild every image

Uses macOS `sips` for resizing, so no extra dependencies.
"""
import hashlib, json, re, shutil, subprocess, sys, unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ACERVO = ROOT / "acervo"
OUT = ROOT / "assets" / "img"
FULL_PX, THUMB_PX, QUALITY = 1600, 720, 78
IMG_EXT = {".png", ".jpg", ".jpeg", ".webp", ".gif"}
SKIP = re.compile(r"(c[oó]pia| 2\.\w+$| \(\d\)\.)", re.I)  # Finder duplicates


def slugify(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def sips(src, dst, px):
    subprocess.run(["sips", "-s", "format", "jpeg", "-s", "formatOptions", str(QUALITY),
                    "-Z", str(px), str(src), "--out", str(dst)],
                   check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def size_of(path):
    out = subprocess.run(["sips", "-g", "pixelWidth", "-g", "pixelHeight", str(path)],
                         capture_output=True, text=True).stdout
    w = re.search(r"pixelWidth: (\d+)", out); h = re.search(r"pixelHeight: (\d+)", out)
    return (int(w.group(1)), int(h.group(1))) if w and h else (0, 0)


def collect(sources):
    files, seen = [], set()
    for rel in sources:
        d = ACERVO / rel
        if not d.is_dir():
            print(f"  ! missing folder: {rel}"); continue
        for f in sorted(d.iterdir(), key=lambda p: p.name.lower()):
            if f.suffix.lower() not in IMG_EXT or SKIP.search(f.name):
                continue
            digest = hashlib.md5(f.read_bytes()).hexdigest()
            if digest in seen:
                continue
            seen.add(digest); files.append(f)
    return files


def main():
    if "--clean" in sys.argv and OUT.exists():
        shutil.rmtree(OUT)
    data = json.loads((ROOT / "content" / "projects.json").read_text())
    projects = []
    for p in data["projects"]:
        if p.get("draft"):
            continue
        print(f"• {p['title']}")
        files = collect(p.get("sources", []))
        if p.get("cover"):  # optional: original file name (or its slug) to use as cover
            c = p["cover"]
            files.sort(key=lambda f: not (f.name == c or slugify(f.stem)[:40] == c))
        if p.get("process"):  # optional: folders whose images fill the 4 "processo" slots
            files = files[:1] + collect(p["process"])[:4] + files[1:]
        files = files[: p.get("maxImages", 14)]
        outdir = OUT / p["slug"]; outdir.mkdir(parents=True, exist_ok=True)
        images = []
        for i, f in enumerate(files):
            base = f"{i:02d}-{slugify(f.stem)[:40]}"
            if f.suffix.lower() == ".gif" and f.stat().st_size < 4_000_000:
                full = outdir / f"{base}.gif"; thumb = full
                if not full.exists(): shutil.copy2(f, full)
            else:
                full, thumb = outdir / f"{base}.jpg", outdir / f"{base}-t.jpg"
                if not full.exists(): sips(f, full, FULL_PX)
                if not thumb.exists(): sips(f, thumb, THUMB_PX)
            w, h = size_of(full)
            images.append({"src": full.relative_to(ROOT).as_posix(),
                           "thumb": thumb.relative_to(ROOT).as_posix(), "w": w, "h": h})
        # drop stale files from previous builds
        keep = {Path(i["src"]).name for i in images} | {Path(i["thumb"]).name for i in images}
        for old in outdir.iterdir():
            if old.name not in keep: old.unlink()
        print(f"    {len(images)} images")
        proj = {k: v for k, v in p.items() if k not in ("sources", "maxImages", "cover", "draft")}
        proj["images"] = images
        projects.append(proj)

    payload = {"order": data["order"], "projects": {p["slug"]: p for p in projects}}
    js = "// Generated by scripts/build.py — edit content/projects.json instead.\n"
    js += "window.SITE = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n"
    (ROOT / "content" / "data.js").write_text(js)
    total = sum(f.stat().st_size for f in OUT.rglob("*") if f.is_file())
    print(f"\nDone: {len(projects)} projects, assets {total / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
